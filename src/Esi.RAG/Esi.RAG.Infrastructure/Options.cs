namespace Esi.RAG.Infrastructure;

public sealed class RagOptions
{
    public string RepositoryPath { get; init; } = ".";

    public string[] ExcludedDirectories { get; init; } =
        [".git", ".vs", "bin", "obj", "node_modules", ".idea", "packages", "dist", "artifacts"];

    public string[] IncludedExtensions { get; init; } =
        [".cs", ".csproj", ".sln", ".sql", ".js", ".jsx", ".ts", ".tsx", ".scss", ".css", ".html", ".htm",
         ".xsl", ".xslt", ".md", ".markdown", ".txt", ".json", ".yaml", ".yml", ".xml", ".config", ".props",
         ".targets", ".resx", ".razor", ".cshtml", ".vb", ".fs"];

    /// <summary>Files larger than this are skipped and reported in the ingestion report.</summary>
    public long MaxFileSizeBytes { get; init; } = 2_000_000;

    /// <summary>Filename glob patterns treated as generated/build output and excluded from indexing.</summary>
    public string[] GeneratedPathPatterns { get; init; } =
        ["*.designer.cs", "*.g.cs", "*.g.i.cs", "*assemblyinfo.cs", "*.min.js", "*.min.css", "*.generated.cs"];

    /// <summary>Markers checked in the first few lines of a file to detect generated content.</summary>
    public string[] GeneratedContentMarkers { get; init; } =
        ["<auto-generated", "// <auto-generated", "this code was generated by a tool", "@generated", "do not edit this file"];

    /// <summary>Filename glob patterns treated as likely secrets and excluded from indexing.</summary>
    public string[] SecretFileNamePatterns { get; init; } =
        ["*.pfx", "*.p12", "*.pem", "*.key", "*.env", ".env*", "id_rsa*", "*.credentials", "*.snk"];

    /// <summary>Regex patterns checked against file content to detect embedded secrets/credentials.</summary>
    public string[] SecretContentPatterns { get; init; } =
        [
            @"-----BEGIN (RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----",
            @"AKIA[0-9A-Z]{16}",
            @"xox[baprs]-[0-9A-Za-z-]{10,48}",
            @"gh[pousr]_[A-Za-z0-9]{20,}",
            @"(?i)password\s*=\s*[""'][^""']{4,}[""']",
            @"(?i)(secret|apikey|api_key)\s*[:=]\s*[""'][^""']{6,}[""']",
        ];

    public int ChunkMaxLines { get; init; } = 80;

    public int ChunkOverlapLines { get; init; } = 12;

    public int EmbeddingConcurrency { get; init; } = 2;

    public int UpsertBatchSize { get; init; } = 256;

    public int ValidatedEmbeddingConcurrency => Math.Max(1, EmbeddingConcurrency);

    public int ValidatedUpsertBatchSize => Math.Clamp(UpsertBatchSize, 128, 512);
}

